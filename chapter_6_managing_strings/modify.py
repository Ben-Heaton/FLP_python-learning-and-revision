# A string object.
string = "Python in Easy Steps"

# Various methods can modify the object.
print("\nCapitalized:\t", string.capitalize())
print("\nTitled:\t", string.title())
print("\nCentred:\t", string.center(30, '*'))
print("\nUpper Case:\t", string.upper())
print("\nJoined:\t", string.join('**'))
print("\nReplaced:\t", string.replace("s", '*'))