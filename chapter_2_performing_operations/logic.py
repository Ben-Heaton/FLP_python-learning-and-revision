a = True
b = False

# Both conditions have to agree
print('AND Logic')
print("a and a =", a and a)
print("a and b =", a and b)
print("b and b =", b and b)

# Either condition has to agree
print('\nOR Logic')
print("a or a =", a or a)
print("a or b =", a or b)
print("b or b =", b or b)

# the reverse of the condition is true
print('\nNOT Logic')
print("a =", not a)
print("b =", not b)