a = 8
b = 2
print("If a =", a, "and b = ", b)

# Addition
print("Addition:\t a + b =", a + b)

# Subtraction
print("Subtraction:\t a - b =", a - b)

# Multiplication
print("Multiplication:\t a * b =", a * b)

# Division
print("Division:\t a / b =", a / b)

# Floor Divsion (leaves no floating point)
print("Floor Division:\t a // b =", a - b)

# Modulo (the remainder)
print("Modulo:\t\t a % b =", a % b)

# Exponent
print("Exponent:\t a ** b =", a ** b)