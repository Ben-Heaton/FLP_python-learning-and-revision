a = 8
b = 4

print("Assign values:\t\t", "a =", a, "\t\tb =", b)

# Add & Assign
a += b
print("Add & Assign:\t\t", "a += b\t\t", a)

# Subtract & Assign
a -= b
print("Subtract & Assign:\t", "a -= b\t\t", a)

# Multiply & Assign
a *= b
print("Multiply & Assign:\t", "a *= b\t\t", a)

# Divide & Assign
a /= b
print("Divide & Assign:\t", "a *= b\t\t", a)

# Modulo & Assign
a %= b
print("Modulo & Assign:\t", "a *= b\t\t", a)