# A list
months = ['January', 'February', 'March']
print("\nFirst month:", months[0])
print("Second month:", months[1])
print("Third month:", months[2])

# 2D List
coords = [[1, 2, 3], [4, 5, 6]]
print("\nTop Left 0,0:", coords[0][0])
print("Bottom Right:", coords[1][2])

# Selecting a string character
print("\nSecond Month First Character:", months[1][0])